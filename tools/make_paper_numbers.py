"""Generate paper_output/numbers.tex and paper_output/tables/*.tex from results/*/{metrics,tc}.json.
The paper never contains a number that is not produced here. Missing results print as '--'.

  python tools/make_paper_numbers.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'results')
OUT = os.path.join(ROOT, 'paper_output')


def load(exp):
    d = os.path.join(RES, exp)
    if not os.path.exists(os.path.join(d, 'metrics.json')):
        return None
    m = json.load(open(os.path.join(d, 'metrics.json')))
    if os.path.exists(os.path.join(d, 'tc.json')):
        m['tc'] = json.load(open(os.path.join(d, 'tc.json')))
    return m


def get(exp, key):
    m = load(exp)
    if m is None:
        return None
    if key == 'mIoU':
        return m['mIoU']
    if key in ('VC8', 'VCc8'):
        v = m['VC' if key == 'VC8' else 'VCc']
        return v.get('8', v.get(8))
    if key in ('TC', 'TA'):
        return m.get('tc', {}).get(key)
    if key in ('GT_TC', 'GT_TA'):
        return m.get('tc', {}).get('ref_GT', {}).get(key[3:])
    raise KeyError(key)


def f1(x):
    return '--' if x is None else f'{x:.1f}'


def sgn(x):
    """Gains for running text ('improves by 6.8'); a negative value keeps its minus sign."""
    return '--' if x is None else f'{x:.1f}'


def diff(a, b):
    return None if a is None or b is None else a - b


def table(path, caption, label, header, rows, colspec, groups=None):
    """groups: optional list of (title, n_columns) for a header row above `header` (first column excluded)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    wide = len(header) > 8
    env, width = ('table*', r'\textwidth') if wide else ('table', r'\columnwidth')
    lines = [rf'\begin{{{env}}}[t]\centering\small', rf'\caption{{{caption}}}\label{{{label}}}',
             r'\setlength{\tabcolsep}{3.5pt}', rf'\begin{{adjustbox}}{{max width={width}}}',
             rf'\begin{{tabular}}{{{colspec}}}', r'\toprule']
    if groups:
        lines.append(' & ' + ' & '.join(rf'\multicolumn{{{k}}}{{c}}{{{g}}}' for g, k in groups) + r' \\')
        col, rules = 2, []
        for _, k in groups:
            rules.append(rf'\cmidrule(lr){{{col}-{col + k - 1}}}')
            col += k
        lines.append(' '.join(rules))
    lines += [' & '.join(header) + r' \\', r'\midrule']
    for r in rows:
        lines.append(r'\midrule' if r == 'mid' else ' & '.join(r) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', r'\end{adjustbox}', rf'\end{{{env}}}']
    open(path, 'w').write('\n'.join(lines) + '\n')


DS3 = ('kitti_step_val', 'camvid_val', 'camvid_test')


def run(ds, key, head='', online=False):
    return f'{ds}__trk2{"on" if online else ""}{head}__{key}'


def main():
    os.makedirs(OUT, exist_ok=True)
    n = {}
    K = DS3[0]
    full = {ds: get(run(ds, 'full'), 'mIoU') for ds in DS3}
    pf = {ds: get(run(ds, 'perframe'), 'mIoU') for ds in DS3}
    bi = {ds: get(run(ds, 'bidir'), 'mIoU') for ds in DS3}
    n['kvalFull'] = f1(full[K])
    n['kvalOracle'] = f1(get(run(K, 'full_oraclepres'), 'mIoU'))
    for short, ds in (('kval', DS3[0]), ('cvval', DS3[1]), ('cvtest', DS3[2])):
        n[f'{short}GainPF'] = sgn(diff(full[ds], pf[ds]))
        n[f'{short}GainFlow'] = sgn(diff(full[ds], bi[ds]))
        n[f'{short}GainOnline'] = sgn(diff(get(run(ds, 'full', online=True), 'mIoU'),
                                           get(run(ds, 'raftema', online=True), 'mIoU')))
    n['kvalPFtc'] = f1(get(run(K, 'perframe'), 'TC'))
    n['kvalGTtc'] = f1(get(run(K, 'perframe'), 'GT_TC'))
    heads = [('', 'Proxy (DINO B/16)'), ('_maskclip', 'MaskCLIP'), ('_sclip', 'SCLIP-style'), ('_naclip', 'NACLIP-style')]
    gains = [diff(get(run(ds, 'full', h), 'mIoU'), get(run(ds, 'perframe', h), 'mIoU')) for h, _ in heads for ds in DS3]
    gains = [g for g in gains if g is not None]
    n['plugGainMin'] = sgn(min(gains)) if gains else '--'
    n['plugGainMax'] = sgn(max(gains)) if gains else '--'
    with open(os.path.join(OUT, 'numbers.tex'), 'w') as fh:
        fh.write('% generated by tools/make_paper_numbers.py -- do not edit\n')
        for k, v in n.items():
            fh.write(f'\\newcommand{{\\{k}}}{{{v}\\xspace}}\n')

    def cells(ds, key, metrics, online=False, head=''):
        return [f1(get(run(ds, key, head, online), m)) for m in metrics]

    # main table: online group and offline group
    M = ('mIoU', 'VCc8', 'TC')
    rows = [['Per-frame'] + sum([cells(ds, 'perframe', M) for ds in DS3], []), 'mid']
    for key, name, online in (('raftema', 'RAFT-EMA', True), ('framepool', '+ mask pooling', True),
                              ('full', r'\textbf{\ours (online)}', True), 'mid',
                              ('bidir', 'Flow smoother', False), ('framepool', '+ mask pooling', False),
                              ('full', r'\textbf{\ours (offline)}', False)):
        if key == 'm':
            rows.append('mid')
            continue
        rows.append([name] + sum([cells(ds, key, M, online) for ds in DS3], []))
    rows += ['mid', [r'\textit{GT (reference)}'] + sum([['100', '--', f1(get(run(ds, 'perframe'), 'GT_TC'))]
                                                       for ds in DS3], [])]
    table(os.path.join(OUT, 'tables', 'results.tex'),
          'Held-out results with the Proxy (DINO B/16) per-frame model. Online methods (top) use only past frames, '
          'offline methods (bottom) the whole clip. KITTI-STEP val (10\\,fps), CamVid val (0016E5, 15\\,Hz) and '
          'CamVid test (1\\,Hz) are never used for tuning.', 'tab:main',
          ['Method'] + ['mIoU', 'VCc$_8$', 'TC'] * 3, rows, 'l' + 'c' * 9,
          groups=[('KITTI-STEP val', 3), ('CamVid val', 3), ('CamVid test (1\\,Hz)', 3)])

    # plug-and-play (offline + online), mIoU on the three held-out sets
    rows = []
    for h, name in heads:
        for key, lab, online in (('perframe', name, False), ('raftema', r'\quad + RAFT-EMA', True),
                                 ('full', r'\quad + \ours (online)', True), ('bidir', r'\quad + flow smoother', False),
                                 ('full', r'\quad + \textbf{\ours (offline)}', False)):
            rows.append([lab] + [f1(get(run(ds, key, h, online), 'mIoU')) for ds in DS3])
        rows.append('mid')
    table(os.path.join(OUT, 'tables', 'plug.tex'), 'Plug-and-play (mIoU): \\ours on four per-frame models, with '
          'fusion parameters selected on KITTI-STEP dev for the Proxy model only.', 'tab:plug',
          ['Per-frame model', 'KITTI val', 'CamVid val', 'CamVid test'], rows[:-1], 'lccc')

    # ablation (offline), mIoU on the three sets + KITTI consistency
    abl = [('perframe', 'Per-frame'), ('crop_debias', 'Debiased crop classification only'),
           ('bidir', 'Flow smoother'), ('framepool', '+ per-frame mask pooling'), ('bidir_tube', '+ tube pooling'),
           ('full_v1', '+ crops ($b{=}0.5$, no debiasing)'), ('full_nodebias', '+ crops ($b{=}2$, no debiasing)'),
           ('full', r'+ crops ($b{=}2$) + class debiasing (\ours)'),
           ('full_oraclepres', r'\textit{\ours + oracle clip presence}')]
    rows = [[name] + [f1(get(run(ds, key), 'mIoU')) for ds in DS3] + cells(K, key, ('VCc8', 'TC')) for key, name in abl]
    table(os.path.join(OUT, 'tables', 'ablation.tex'), 'Ablation (offline): mIoU on the three held-out sets and '
          'consistency on KITTI-STEP val.', 'tab:ablation',
          ['Variant', 'KITTI', 'CamVid val', 'CamVid test', 'VCc$_8$', 'TC'], rows, 'lccccc')

    # SAM 3 reference (concept-supervised)
    rows = []
    for key, name in (('perframe', 'SAM\\,3 per frame'), ('bidir', '\\quad + flow smoother'),
                      ('full', '\\quad + \\ours')):
        rows.append([name] + sum([cells(ds, key, ('mIoU', 'VCc8'), head='_sam3') for ds in DS3], []))
    rows += ['mid', [r'\ours on Proxy (training-free)'] + sum([cells(ds, 'full', ('mIoU', 'VCc8')) for ds in DS3], [])]
    table(os.path.join(OUT, 'tables', 'sam3.tex'), 'SAM\\,3~\\cite{carion2025sam3}, trained with large-scale '
          'concept-level mask supervision, used per frame with one text prompt per class (instance masks, selected on '
          'KITTI-STEP dev), and wrapped by \\ours.', 'tab:sam3',
          ['Method'] + ['mIoU', 'VCc$_8$'] * 3, rows, 'lcccccc',
          groups=[('KITTI-STEP val', 2), ('CamVid val', 2), ('CamVid test', 2)])
    n2 = {'samKval': f1(get(run(K, 'perframe', '_sam3'), 'mIoU')), 'samCvval': f1(get(run(DS3[1], 'perframe', '_sam3'), 'mIoU')),
          'samCvtest': f1(get(run(DS3[2], 'perframe', '_sam3'), 'mIoU'))}
    with open(os.path.join(OUT, 'numbers.tex'), 'a') as fh:
        for k, v in n2.items():
            fh.write(f'\\newcommand{{\\{k}}}{{{v}\\xspace}}\n')
    print(json.dumps(n, indent=1))


if __name__ == '__main__':
    main()
